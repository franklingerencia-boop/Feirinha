export type EventDay = { id: string; day: string; open_time: string | null; close_time: string | null; setup_time: string | null; teardown_time: string | null };
export type StallType = { id: string; name: string; size_label: string | null; fee_cents: number; fee_mode: "per_day" | "per_event"; color: string };
