  discount_cents: number;
  due_date: string | null;
  notes: string | null;
  source: string;
  trade_name: string;
  responsible_name: string | null;
  vendor_phone: string | null;
  vendor_whatsapp: string | null;
  vendor_email: string | null;
  vendor_segment: string | null;
  linked_company_id: string | null;
  days_count: number;
